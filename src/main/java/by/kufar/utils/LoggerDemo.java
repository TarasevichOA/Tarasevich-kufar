package by.kufar.utils;

import org.apache.logging.log4j.LogManager;
import org.apache.logging.log4j.Logger;

/**
 * Пример демонстрационного класса для работы с логированием Log4j2.
 * В реальном проекте этот код пишется внутри тестов или Page Object классов.
 */
public class LoggerDemo {

    // Создаем экземпляр логгера для текущего класса.
    // LogManager автоматически определяет имя класса, чтобы в логах было видно, откуда пришла запись.
    private static final Logger logger = LogManager.getLogger(LoggerDemo.class);

    /**
     * Точка входа для демонстрации (в реальных UI-тестах этот метод не нужен,
     * там код исполняется внутри тестовых методов @Test).
     */
    public static void main(String[] args) {

        // Информационные логи. Используются для фиксации ключевых действий (открытие страницы, клик, ввод текста).
        logger.info("Hello INFO from logger. Сообщаем о штатном действии в тесте.");

        // Логи-предупреждения. Используются, если что-то пошло не по плану, но тест еще может продолжить работу.
        logger.warn("It is a WARN. Предупреждение о потенциальной проблеме.");

        // Логи-ошибки. Используются для фиксации критических сбоев, падений ассертов или багов приложения.
        logger.error("Here is an ERROR. Запись текстовой ошибки в лог.");

        try {
            // Искусственно вызываем деление на ноль для демонстрации перехвата исключения
            int a = 1 / 0;
        } catch (Exception exception) {

            // ВАЖНО: Передавая exception вторым аргументом, Log4j2 автоматически
            // распечатает в лог весь StackTrace (трассировку стека) с указанием точной строки падения.
            logger.error("Real ERROR with error message: Произошло падение во время выполнения!", exception);
        }
    }
}
